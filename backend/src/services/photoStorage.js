const crypto = require('node:crypto');
const fs = require('node:fs/promises');
const path = require('node:path');
const { uploadDir } = require('../config/env');
const AppError = require('../utils/AppError');

const PHOTO_DIR = path.join(uploadDir, 'patients');

// The real file type is read from the first bytes: the client-provided MIME type can't be trusted.
const SIGNATURES = [
  { extension: 'jpg', contentType: 'image/jpeg', matches: (b) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
  {
    extension: 'png',
    contentType: 'image/png',
    matches: (b) => b.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])),
  },
  {
    extension: 'webp',
    contentType: 'image/webp',
    matches: (b) => b.subarray(0, 4).toString('ascii') === 'RIFF' && b.subarray(8, 12).toString('ascii') === 'WEBP',
  },
];

const CONTENT_TYPES = Object.fromEntries(SIGNATURES.map(({ extension, contentType }) => [extension, contentType]));
// Only names generated by save() are accepted, which rules out any path traversal.
const FILENAME_PATTERN = /^[0-9a-f-]{36}\.(jpg|png|webp)$/;

function detectImageType(buffer) {
  return SIGNATURES.find((signature) => buffer.length >= 12 && signature.matches(buffer));
}

async function save(buffer) {
  const type = detectImageType(buffer);
  if (!type) throw AppError.badRequest('Photo must be a JPEG, PNG or WebP image', 'INVALID_PHOTO');

  await fs.mkdir(PHOTO_DIR, { recursive: true });
  const filename = `${crypto.randomUUID()}.${type.extension}`;
  await fs.writeFile(path.join(PHOTO_DIR, filename), buffer);
  return filename;
}

function resolve(filename) {
  if (!FILENAME_PATTERN.test(filename)) return null;
  return { filePath: path.join(PHOTO_DIR, filename), contentType: CONTENT_TYPES[path.extname(filename).slice(1)] };
}

async function remove(filename) {
  const file = filename && resolve(filename);
  if (!file) return;
  await fs.rm(file.filePath, { force: true });
}

module.exports = { save, resolve, remove };
